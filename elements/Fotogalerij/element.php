    static function dependencies()
    {
        return ['0' =>  ['inlineScripts' => ['(function () {
  if (window.pdkFg) return;
  window.pdkFg = true;
  /* GLightbox komt uit de Libraries-map van PDK Theme Options. De laadvolgorde van bibliotheek en dit script is niet gegarandeerd, dus GLightbox wordt pas bij de klik opgezocht. Zonder GLightbox opent de link gewoon de grote foto. */
  document.addEventListener("click", function (e) {
    var a = e.target.closest ? e.target.closest(".fotogalerij__link") : null, list, links, items = [], i = 0, j;
    if (!a || !window.GLightbox || e.button > 0 || e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
    list = a.closest(".fotogalerij__lijst");
    if (!list) return;
    /* per galerij een eigen lightbox, zodat meerdere galerijen op één pagina los blijven */
    if (!list.pdkLightbox) {
      links = list.querySelectorAll(".fotogalerij__link");
      for (j = 0; j < links.length; j++) items.push({ href: links[j].href, type: "image", title: links[j].getAttribute("data-title") || "" });
      list.pdkLightbox = window.GLightbox({ elements: items });
    }
    links = list.querySelectorAll(".fotogalerij__link");
    for (j = 0; j < links.length; j++) if (links[j] === a) i = j;
    e.preventDefault();
    list.pdkLightbox.openAt(i);
  });
})();'],'builderCondition' => 'return false;','frontendCondition' => 'return true;','title' => 'Fotogalerij - frontend',],];
